import Foundation
import Testing
@testable import OrakulCore

/// Обещание продукта — «поиск по словам, а не по смыслу» — держится на том, что
/// слово в вопросе и слово в расшифровке сходятся в одну основу. По-русски они
/// почти никогда не совпадают буквами: спрашивают «по развёртыванию», а на
/// звонке говорили «развёртывание».
///
/// Разряд на «-ние» разъезжался целиком: «развёртывание» обрезалось до
/// «развёртыван» (окончание «ие»), а любая косвенная форма — до
/// «развёртывани» (окончание «ем», «я», «ю»). Две разные основы у одного
/// слова, то есть честное «не говорили» о том, что говорили. Ни один тест
/// этого не ловил: 3006 проверок проходили и до починки.
@Suite("Падежи в поиске")
struct RussianCaseSearchTests {

    private func session(_ text: String) -> RecallIndex {
        RecallIndex(sessions: [.init(id: "A", title: "Планёрка", date: "2026-08-14", digest: text)])
    }

    /// Слова этого разряда — самые обычные в разговоре про работу.
    @Test("косвенная форма находит именительную",
          arguments: [
            ("развёртывание откладываем",
             ["развёртывания", "развёртыванию", "развёртыванием", "развёртывании",
              "развёртываниями", "развёртываниях"]),
            ("обновление выкатим в среду",
             ["обновления", "обновлению", "обновлением", "обновлении"]),
            ("подключение к трекеру сделали",
             ["подключения", "подключению", "подключением"]),
            ("решение приняли вчера",
             ["решения", "решению", "решением", "решений"]),
            ("тестирование прошли",
             ["тестирования", "тестированию", "тестированием"]),
            ("согласование затянулось",
             ["согласования", "согласованию", "согласованием"]),
          ])
    func obliqueFindsNominative(said: String, asked: [String]) {
        let index = session(said)
        for question in asked {
            #expect(!index.search(question).isEmpty,
                    "спросили «\(question)» — не нашли «\(said)»")
        }
    }

    /// И обратно: сказали в косвенном падеже, спрашивают в именительном.
    @Test("именительная форма находит косвенную")
    func nominativeFindsOblique() {
        #expect(!session("по развёртыванию договорились").search("развёртывание").isEmpty)
        #expect(!session("занимаемся обновлением").search("обновление").isEmpty)
        #expect(!session("вопрос по согласованию").search("согласование").isEmpty)
    }

    /// Разряд на «-ия» тоже сходится — в свою основу, более короткую.
    @Test("слова на «-ия» сходятся между собой")
    func iaClassAgrees() {
        let index = session("линия связи и партия сборки")
        for question in ["линии", "линией", "линию", "партии", "партией"] {
            #expect(!index.search(question).isEmpty, "спросили «\(question)» — не нашли")
        }
    }

    /// Проверка не должна проходить оттого, что находится вообще всё.
    @Test("слово, которого не было, по-прежнему не находится")
    func unrelatedWordStillMisses() {
        let index = session("развёртывание откладываем")
        #expect(index.search("корпоратив").isEmpty)
        #expect(index.search("увольнение").isEmpty, "«увольнение» не сказано — находиться нечему")
    }

    /// Прилагательные разъезжались на творительном: «годовой» обрезался до
    /// «годов», а «годовым» оставался целым — «что решили по годовому тарифу»
    /// не находило разговор о годовом тарифе.
    @Test("прилагательное находится в любом падеже")
    func adjectiveCasesAgree() {
        let index = session("годовой тариф не трогаем, месячный поднимаем")
        for question in ["годовым", "годового", "годовому", "годовая", "годовые",
                         "годовых", "месячным", "месячного"] {
            #expect(!index.search(question).isEmpty, "спросили «\(question)» — не нашли")
        }
    }

    /// Короткие слова не режутся вовсе, и это защищает от ложных совпадений:
    /// «режим» не должен превращаться в «реж» и находить «режет».
    @Test("короткое слово не обрезается до бессмыслицы")
    func shortWordsAreLeftAlone() {
        #expect(session("режим работы обсудили").search("режет").isEmpty)
        #expect(!session("режим работы обсудили").search("режим").isEmpty)
    }

    /// Дефис оставлен внутри слова нарочно: «код-свитчинг» — одно слово. Но
    /// искали только целиком, и вопрос «что там с кластером» не находил
    /// «Kubernetes-кластер», хотя произнесли именно это.
    @Test("составное слово находится и целиком, и по частям")
    func compoundWordsFindTheirParts() {
        let index = session("обсудили код-свитчинг и Kubernetes-кластер")
        for question in ["код-свитчинг", "свитчинг", "кластер", "Kubernetes",
                         "Kubernetes-кластер"] {
            #expect(!index.search(question).isEmpty, "спросили «\(question)» — не нашли")
        }
    }

    /// Дефис по краям — знак препинания, а не часть слова: строка «- тарифы»,
    /// вставленная из списка, давала токен «-тарифы», не совпадавший ни с чем.
    @Test("дефис по краям слова не мешает найти")
    func edgeHyphensAreTrimmed() {
        let index = session("по тарифам решили не трогать годовой")
        for question in ["-тарифы", "тарифы-", "--тарифы"] {
            #expect(!index.search(question).isEmpty, "спросили «\(question)» — не нашли")
        }
    }

    /// И обратная сторона: части не должны склеивать несвязанное.
    @Test("часть составного слова не находит чужой разговор")
    func partsDoNotMatchEverything() {
        #expect(session("обсудили Kubernetes-кластер").search("корпоратив").isEmpty)
        #expect(session("обсудили Kubernetes-кластер").search("нагрузка").isEmpty)
    }

    /// Обрезка краёв не видна по «нашлось/не нашлось»: «-тарифы» и так
    /// распадается на части. Видна она в самом указателе — лишний токен
    /// «-тариф» там ничей и только разбавляет вес редких слов.
    @Test("дефис по краям не оставляет мусорного слова в указателе")
    func edgeHyphenLeavesNoJunkToken() {
        #expect(RecallIndex.tokens("-тарифы") == ["тариф"])
        #expect(RecallIndex.tokens("тарифы-") == ["тариф"])
        #expect(RecallIndex.tokens("- тарифы -") == ["тариф"])
    }

    /// Целое слово остаётся рядом с частями. По «нашлось/не нашлось» это не
    /// видно (запрос распадается так же, как расшифровка), и по порядку выдачи
    /// тоже: в обоих случаях у документов одни и те же части. Первая попытка
    /// сравнивала именно порядок и проходила при выброшенном целом слове —
    /// проверка, которой всё равно, что она проверяет. Смотреть надо на сам
    /// указатель: целое слово в нём есть, и оно отличает разговор, где
    /// произнесли составное слово, от разговора, где встретились две части.
    @Test("составное слово попадает в указатель целиком, а не только частями")
    func compoundKeepsTheWholeToken() {
        let parsed = RecallIndex.tokens("обсудили код-свитчинг")
        #expect(parsed.contains("код-свитчинг"),
                "целое слово пропало из указателя: \(parsed)")
        #expect(parsed.contains("код") && parsed.contains("свитчинг"),
                "части пропали из указателя: \(parsed)")
        // И у слова без дефиса ничего лишнего не появляется.
        #expect(RecallIndex.tokens("тарифы") == ["тариф"])
    }
}
