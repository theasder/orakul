import Foundation
import Testing
@testable import OrakulCore

/// Опечатка в вопросе — и продукт утверждал, что разговора не было.
///
/// «тарифф» с лишней буквой не совпадает ни с чем, поиск словарный, и человек
/// читал «в сохранённых звонках об этом не говорили» — приговор теме, которую
/// обсуждали двумя строками выше. Проверяется здесь именно это: не «функция
/// расстояния работает», а «продукт перестал врать про свой же архив».
@Suite("Опечатка в вопросе")
struct NearMissTests {

    private let index = RecallIndex(sessions: [
        RecallIndex.Session(
            id: "1", title: "Планёрка", date: "2026-08-14",
            digest: """
            Аня: По тарифам — что решили в итоге?
            Борис: Годовой не трогаем до декабря, месячный поднимаем на пятнадцать процентов.
            Аня: А деплой раскатываем когда?
            Борис: В пятницу, если тесты зелёные.
            """),
    ])

    /// Четыре опечатки, которыми человек в самом деле промахивается.
    ///
    /// Все — в основе слова. Промах в окончании подсказки не требует: «тарифя»
    /// поиск находит сам, потому что окончание он и так отбрасывает. Первый
    /// вариант этой проверки требовал подсказку и на «тарифя» — то есть
    /// требовал чинить то, что не сломано.
    @Test("Слово с опечаткой подсказывается", arguments: [
        ("тарифф", "тарифам"),      // лишняя буква
        ("тарф", "тарифам"),        // пропущенная
        ("торифам", "тарифам"),     // не та
        ("таирфам", "тарифам"),     // переставленные соседние
        ("деплй", "деплой"),
        ("рскатываем", "раскатываем"),
    ])
    func подсказывает(_ спрошено: String, _ ожидается: String) {
        let подсказки = index.nearMisses(for: спрошено)
        #expect(подсказки.contains(ожидается),
                "«\(спрошено)» не подсказало «\(ожидается)»: \(подсказки)")
    }

    /// Подсказка — то, что человек прочтёт и наберёт. Основа «раскатыва» не
    /// слово, и предложить её значит выдать за русский язык внутренний формат.
    @Test("Подсказка — живое слово, а не основа")
    func живоеСлово() throws {
        let подсказки = index.nearMisses(for: "рскатываем")
        let слово = try #require(подсказки.first)
        #expect(слово == "раскатываем")
        #expect(слово != RecallIndex.stem("раскатываем"))
    }

    /// И это слово обязано находиться: подсказка, по которой не ищется, —
    /// вторая ложь поверх первой.
    @Test("По подсказке действительно находится")
    func подсказкаНаходится() throws {
        let слово = try #require(index.nearMisses(for: "тарифф").first)
        #expect(!index.search(слово).isEmpty, "«\(слово)» подсказали, но не находят")
    }

    /// Слова, которого в архиве нет, — нет. Молчание здесь дороже подсказки:
    /// придумать похожее к «криптовалюте» значит вернуть ту же выдумку,
    /// от которой продукт и отказывается.
    @Test("Чужому слову подсказки нет", arguments: ["криптовалюта", "ипотека", "маркетинг"])
    func чужомуСловуМолчим(_ слово: String) {
        let подсказки = index.nearMisses(for: слово)
        #expect(подсказки.isEmpty, "«\(слово)»: \(подсказки)")
    }

    /// Короткому слову одна буква — треть слова. «код» и «кот» на таком
    /// расстоянии неразличимы, и подсказка вырождается в шум.
    @Test("Коротким словам не подсказываем")
    func короткиеМолчат() {
        let короткий = RecallIndex(sessions: [
            RecallIndex.Session(id: "1", title: "Разбор", date: "2026-08-14",
                                digest: "Аня: код смотрели вчера"),
        ])
        #expect(короткий.nearMisses(for: "кот").isEmpty)
    }

    /// Слово, которое в архиве есть, подсказки не требует — даже когда рядом
    /// лежит похожее. Иначе на найденное слово продукт отвечал бы «похоже на
    /// опечатку», то есть сомневался в том, что сам только что нашёл.
    ///
    /// Архив нарочно содержит и «тарифы», и «тарифф»: без отбора по словарю
    /// второе предлагалось бы вместо первого.
    @Test("Слову из архива подсказки не нужно")
    func своёСловоБезПодсказки() {
        let сдвойником = RecallIndex(sessions: [
            RecallIndex.Session(id: "1", title: "Планёрка", date: "2026-08-14",
                                digest: "Аня: тарифы смотрели\nБорис: тарифф это опечатка"),
        ])
        #expect(сдвойником.nearMisses(for: "тарифы").isEmpty,
                "\(сдвойником.nearMisses(for: "тарифы"))")
    }

    @Test("Пустой архив молчит")
    func пустойМолчит() {
        #expect(RecallIndex(sessions: []).nearMisses(for: "тарифф").isEmpty)
    }

    // MARK: - Расстояние

    @Test("Одна опечатка — это одна опечатка", arguments: [
        ("тариф", "тарифф"),        // вставка
        ("тарифф", "тариф"),        // удаление
        ("тариф", "тарид"),         // замена
        ("тариф", "тарфи"),         // перестановка соседних
    ])
    func однаОпечатка(_ левое: String, _ правое: String) {
        #expect(RecallIndex.isOneEditApart(левое, правое))
    }

    /// Обратная сторона: слишком далёкое не должно считаться опечаткой, иначе
    /// подсказка станет случайным словом из архива.
    @Test("Далёкое опечаткой не считается", arguments: [
        ("тариф", "тариф"),         // то же слово — не подсказка
        ("тариф", "тарффф"),        // две вставки
        ("тариф", "деплой"),        // разные слова
        ("тариф", "тарифам"),       // ровно две буквы разницы
        ("тарифам", "тариф"),       // и она же в другую сторону
        ("тариф", "тарифами"),      // разница длины больше одной
        ("тариф", "атрифы"),        // перестановка плюс замена
        ("", "тариф"),
    ])
    func далёкоеНеОпечатка(_ левое: String, _ правое: String) {
        #expect(!RecallIndex.isOneEditApart(левое, правое))
    }

    /// Перестановка несоседних букв — не одна опечатка: «тариф» и «фарит»
    /// отличаются двумя заменами, и путать их значит подсказывать наугад.
    @Test("Переставлять можно только соседние")
    func толькоСоседние() {
        #expect(!RecallIndex.isOneEditApart("тариф", "фарит"))
        #expect(RecallIndex.isOneEditApart("тариф", "атриф"))
    }

    // MARK: - Ответ целиком

    @Test("Отказ несёт подсказку")
    func отказСПодсказкой() {
        let ответ = RecallAnswer.compose(query: "тарифф", hits: [],
                                         suggestions: ["тарифам"])
        #expect(ответ.contains("«тарифам»"))
        #expect(ответ.contains("Похоже на опечатку"))
        // Отказ придумывать остаётся: подсказка его дополняет, а не отменяет.
        #expect(ответ.contains("придумывать не буду"))
    }

    @Test("Без подсказок лишней строки нет")
    func безПодсказокЧисто() {
        let ответ = RecallAnswer.compose(query: "криптовалюта", hits: [])
        #expect(!ответ.contains("опечат"))
        #expect(ответ.split(separator: "\n").count == 1)
    }
}
