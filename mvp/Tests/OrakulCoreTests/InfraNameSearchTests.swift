import Foundation
import Testing
@testable import OrakulCore

/// Поиск по именам инфраструктуры на двух алфавитах.
///
/// Найдено запуском собранной команды на расшифровке, какую и наговаривают на
/// планёрке: «подняли редис», «постгрес обновили», «в гите ветку смержили».
/// Спросить те же вещи официальным именем — `Redis`, `PostgreSQL`, `git` — не
/// находило НИ ОДНОГО из девяти проверенных. А это ровно те слова, которыми
/// разработчик пишет в конфиге и читает в документации: по-русски он их
/// говорит, латиницей — ищет.
///
/// Раньше работали только `Kubernetes` и `Docker`: они единственные из этого
/// ряда стояли в таблице вариантов.
///
/// **Почему отдельная таблица, а не общая с переписыванием расшифровки.**
/// `restore` переписывает текст созвона по той же таблице канонов. Половина
/// этих имён совпадает с обычными русскими словами: «редис» — овощ, «кафка» —
/// писатель, «прометей» — титан. Переписать их в расшифровке значит испортить
/// нормальную фразу — сам файл словаря такие слова и исключает намеренно
/// («агент», «канал», «очередь»). А вот СЧЕСТЬ их одним словом при поиске
/// безопасно: худшее, что бывает, — лишняя находка про овощ.
@Suite("Имена инфраструктуры на двух алфавитах")
struct InfraNameSearchTests {

    private func archive(_ text: String) -> RecallIndex {
        RecallIndex(sessions: [.init(id: "1", title: "Планёрка",
                                     date: "2026-08-13", digest: text)])
    }

    @Test("официальное имя находит русское произношение",
          arguments: [("Подняли редис до пятидесяти тысяч ключей.", "Redis"),
                      ("Кафку сегодня не трогали.", "Kafka"),
                      ("Постгрес обновили до шестнадцатой.", "PostgreSQL"),
                      ("Нжинкс перенастроили под новый домен.", "nginx"),
                      ("В гите ветку смержили.", "git"),
                      ("Эластик переиндексировали.", "Elasticsearch"),
                      ("Кликхаус держит нагрузку.", "ClickHouse"),
                      ("Графану настроили, алерты приходят.", "Grafana"),
                      ("Прометей собирает метрики.", "Prometheus")])
    func officialNameFindsSpokenForm(said: String, asked: String) {
        let hits = archive(said).search(asked)
        #expect(!hits.isEmpty, "«\(asked)» не нашёл «\(said)»")
    }

    @Test("русское произношение по-прежнему находит само себя",
          arguments: ["редис", "кафка", "постгрес", "нжинкс", "гит",
                      "эластик", "кликхаус", "графана", "прометей"])
    func spokenFormStillFindsItself(word: String) {
        // Обратная сторона: если новая таблица собьёт разбор, перестанет
        // работать то, что работало. «гит» до этой правки не работал вовсе —
        // «ит» стоит в списке русских окончаний, и обрезка превращала его в
        // «г», а «гите» — в «гит». Термин в словаре обрезку отменяет.
        let hits = archive("Обсудили \(word) и разошлись.").search(word)
        #expect(!hits.isEmpty, "«\(word)» не нашёл сам себя")
    }

    @Test("падежи официальных имён тоже находятся",
          arguments: [("Постгрес обновили.", "постгресу"),
                      ("Кафку не трогали.", "кафке"),
                      ("В гите ветку смержили.", "гит")])
    func casesResolve(said: String, asked: String) {
        #expect(!archive(said).search(asked).isEmpty, "«\(asked)» не нашёл «\(said)»")
    }

    @Test("расшифровку эти имена НЕ переписывают")
    func transcriptIsNotRewritten() {
        // Граница, ради которой таблица отдельная. «Купили редис и морковь» —
        // это про овощи, и продукт не имеет права превращать их в Redis.
        for phrase in ["Купили редис и морковь.",
                       "Читал Кафку в отпуске.",
                       "Прометей прикован к скале."] {
            #expect(RussianLexicon.restore(phrase) == phrase,
                    "расшифровку переписали: «\(RussianLexicon.restore(phrase))»")
        }
    }

    @Test("общее слово из словаря по-прежнему переписывается")
    func ordinaryTermsStillRestored() {
        // Контроль: если новая таблица случайно подменит собой старую,
        // перестанет работать то, ради чего словарь и заводили.
        #expect(RussianLexicon.restore("Сделали deploy в прод.").contains("деплой"),
                "перестало работать переписывание заимствований")
    }

    /// Добавлено 2026-08-14. Найдено запуском поиска на словах, которые на
    /// созвоне произносят вслух: «стейджинг», «кролик», «артефакт», «откат»,
    /// «ролбэк» не находили ничего.
    @Test("сказанное вслух находится по английскому написанию",
          arguments: [
            ("подняли staging для проверки", ["стейджинг", "staging"]),
            ("очередь в rabbitmq переполнена", ["кролик", "раббит", "rabbitmq"]),
            ("собери artifact в ci", ["артефакт", "artifact"]),
            ("сделали rollback выкатки", ["откат", "ролбэк", "rollback"]),
          ])
    func spokenFormsFindWrittenOnes(said: String, asked: [String]) {
        let index = RecallIndex(sessions: [
            .init(id: "A", title: "Выкатка", date: "2026-08-14", digest: said)])
        for question in asked {
            #expect(!index.search(question).isEmpty,
                    "спросили «\(question)» — не нашли «\(said)»")
        }
    }

    /// Обратная сторона, ради которой эти три слова лежат в таблице поиска, а
    /// не в словаре терминов: расшифровку они не переписывают. «Кролик» бывает
    /// зверем, «откат» — деньгами, «артефакт» — находкой, и подменять их в
    /// чужом разговоре продукт права не имеет.
    @Test("обычные русские слова не переписываются в расшифровке",
          arguments: ["кролик", "откат", "артефакт"])
    func ordinaryWordsSurviveInTheTranscript(word: String) {
        let phrase = "на даче завёлся \(word), вот такая история"
        #expect(RussianLexicon.restore(phrase).contains(word),
                "слово подменили в расшифровке: \(RussianLexicon.restore(phrase))")
    }
}
