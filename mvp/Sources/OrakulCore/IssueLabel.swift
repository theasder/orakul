import Foundation

/// Как задача из трекера подписывается в ответе: `[#314]` или `[#42, closed]`.
///
/// **Почему отдельно, а не строкой на месте.** Эта подпись собиралась в трёх
/// местах одинаковым выражением — в командной строке и дважды в приложении, в
/// веере источников. Когда состояние перестало выдумываться (поиск Redmine его
/// не возвращает, и `[#314, unknown]` читается как «вам неизвестно»), правка
/// дошла до одного места из трёх. Остальные два стали печатать `[#314, ]` —
/// хуже, чем было.
///
/// Такой разрыв в этом продукте уже случался со словарём, с разбором слова и с
/// ответом на пустой архив. Дешевле держать решение в одном месте, чем помнить
/// про все.
public enum IssueLabel {

    /// Состояние приписывается, только если сервис его сообщил.
    ///
    /// «closed» меняет смысл находки на противоположный — «это уже обсудили и
    /// закрыли» не то же, что «висит открытым», — поэтому там, где состояние
    /// есть, оно обязано остаться.
    public static func render(key: String, state: String) -> String {
        let trimmed = state.trimmingCharacters(in: .whitespaces)
        return trimmed.isEmpty ? "[\(key)]" : "[\(key), \(trimmed)]"
    }
}
