import Foundation

/// Прочитать файл расшифровки, не требуя от человека UTF-8.
///
/// **Зачем.** Продукт делается для русской команды, а в русском обиходе полно
/// файлов не в UTF-8: выгрузка из старого инструмента, текст, сохранённый
/// коллегой на Windows, «Юникод» в блокноте (это UTF-16). Читалось строго
/// UTF-8, и на таком файле человек получал «Не смог прочитать файл: <путь>» —
/// сообщение, которое отправляет проверять путь и права, тогда как файл на
/// месте и прекрасно читается. Свой первый настоящий транскрипт русский
/// разработчик приносит именно таким.
///
/// **Порядок не случаен.**
///
/// 1. UTF-8 — канон. Проверяется строго и первым: правильный файл обязан
///    читаться как есть, без догадок.
/// 2. UTF-16 — только с меткой порядка байтов. Без метки его от однобайтовой
///    кодировки не отличить, и гадать здесь нельзя.
/// 3. CP1251 — запасная и последняя.
///
/// **Чем опасен третий шаг.** В CP1251 почти каждый байт — символ, поэтому
/// картинка «читается успешно» и уезжает в архив мусором. Измерено: Foundation
/// отказывается читать в CP1251 набор из всех 256 байт (там есть
/// неопределённый), но заголовок PNG читает прекрасно — и даёт тридцать
/// управляющих символов. Настоящий русский текст в той же кодировке даёт ноль.
/// Это и есть различающий признак, а не «похоже на текст» на глаз.
public enum TranscriptFile {

    /// Управляющие символы, которых в расшифровке быть не может.
    /// Табуляция, перевод строки и возврат каретки — могут.
    private static func looksLikeText(_ text: String) -> Bool {
        !text.unicodeScalars.contains {
            $0.value < 32 && $0 != "\t" && $0 != "\n" && $0 != "\r"
        }
    }

    /// Содержимое файла или nil, если это не текст.
    public static func read(_ path: String) -> String? {
        guard let data = try? Data(contentsOf: URL(fileURLWithPath: path)) else { return nil }
        return decode(data)
    }

    /// Отдельно от чтения с диска, чтобы правило можно было проверить на
    /// байтах, не заводя файл.
    public static func decode(_ data: Data) -> String? {
        if let utf8 = String(data: data, encoding: .utf8) {
            return looksLikeText(utf8) ? utf8 : nil
        }
        // Метка порядка байтов: FF FE или FE FF. Без неё не гадаем.
        let bom = data.prefix(2)
        if bom == Data([0xFF, 0xFE]) || bom == Data([0xFE, 0xFF]),
           let utf16 = String(data: data, encoding: .utf16),
           looksLikeText(utf16) {
            return utf16
        }
        if let cp1251 = String(data: data, encoding: .windowsCP1251),
           looksLikeText(cp1251) {
            return cp1251
        }
        return nil
    }
}
