// Разбор Swift-исходников для проверок, которые не могут этот код выполнить.
//
// Часть кода в прогоне не выполнить: делегату ScreenCaptureKit нужен настоящий
// поток, перезапуску микрофона — настоящее аудиоустройство. Остаётся смотреть в
// текст. Смотреть в текст легко неправильно, и за один вечер это случилось три
// раза подряд:
//
//   1. `/handleRestartFailure/` совпало с ОБЪЯВЛЕНИЕМ метода после того, как
//      сам вызов был вырезан;
//   2. `/restartAfterConfigChangeIfNeeded[\s\S]{0,400}handleRestartFailure\(/`
//      совпало через вызов планировщика, за которым в окно попало то же
//      объявление;
//   3. `/readdirSync/` совпало со строкой импорта, когда вызов убрали.
//
// Общее у всех трёх — окно в N символов вместо настоящих границ. Окно не знает,
// где кончается функция, и цепляет соседний код. Здесь границы считаются по
// скобкам, и «внутри функции» значит внутри функции.

/// Код без комментариев.
///
/// Обязательный первый шаг: в этом репозитории комментарии намеренно цитируют
/// то, чего в коде быть не должно, — и проверка, поймавшая цитату, проверяет
/// комментарий.
export function stripComments(source) {
  return source
    .split('\n')
    .filter((line) => !line.trim().startsWith('//'))
    .join('\n');
}

/// Тело функции по её объявлению — от `{` до парной `}`.
///
/// `signature` — начало строки объявления, например `private func stop()`.
/// Возвращает null, если объявления нет: вызывающий обязан отличить «функция
/// исчезла» от «вызова в ней нет», иначе переименование тихо погасит проверку.
export function bodyOf(source, signature) {
  const code = stripComments(source);
  const start = code.indexOf(signature);
  if (start === -1) return null;

  const open = code.indexOf('{', start);
  if (open === -1) return null;

  let depth = 0;
  for (let i = open; i < code.length; i += 1) {
    if (code[i] === '{') depth += 1;
    else if (code[i] === '}') {
      depth -= 1;
      if (depth === 0) return code.slice(open + 1, i);
    }
  }
  return null;   // незакрытая скобка — пусть решает вызывающий
}

/// Зовёт ли функция `signature` функцию `callee` в своём теле.
///
/// Ищется именно вызов — `callee(`, — а не имя: объявление
/// `func callee(_ error: Error)` содержит имя тоже, и на этом проверка уже
/// попадалась. Возвращает null, если самой функции нет.
export function callsInside(source, signature, callee) {
  const body = bodyOf(source, signature);
  if (body === null) return null;
  // `?` перед скобкой — необязательный вызов Swift: `onStopped?(error)`.
  // Без него помощник не увидел ровно тот вызов, ради которого писался.
  return new RegExp(`\\b${callee}\\s*\\??\\s*\\(`).test(body);
}
