#!/bin/bash
# Идёт ли прямо сейчас сборка образов ЭТОГО репозитория.
#
# Выходит с нулём, если идёт. Ставить первой строкой везде, где скрипт пишет в
# `Sources/` — мутации в том числе: правка файла во время сборки роняет её с
# `input file ... was modified during the build`, и десять минут на две
# архитектуры уходят впустую.
#
# Почему не `pgrep -f`. Сборка запускается как `cd app && bash dist-all.sh`, и
# в командной строке процесса стоит ровно `bash dist-all.sh` — без пути. Шаблон
# `orakul/app.*dist-all\.sh`, написанный, чтобы не ловить чужую сборку, не
# совпадал никогда: он молча разрешал мутировать посреди сборки. Голый
# `pgrep -f dist-all` — другая крайность: он совпадает с собственной командной
# строкой вызывающего и с чужими сборками из /tmp, то есть врёт в другую сторону.
#
# Личность процесса определяется его рабочим каталогом, а не строкой запуска.
# Заодно отсюда пропадает самосовпадение: слова «dist-all» нет в командной
# строке того, кто вызывает этот файл, — оно осталось внутри файла.
set -uo pipefail

# `pwd` без -P печатает логический путь: в /tmp это /var/folders/…, а lsof
# всегда отдаёт физический /private/var/folders/… — сравнение молча не
# совпадало бы у всякого, чей клон лежит за символической ссылкой.
root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)

for pid in $(pgrep -f 'dist-all\.sh' 2>/dev/null); do
    [ "$pid" = "$$" ] && continue
    cwd=$(lsof -a -p "$pid" -d cwd -Fn 2>/dev/null | sed -n 's/^n//p' | head -1)
    [ -z "$cwd" ] && continue
    case "$cwd" in
        "$root"/*|"$root") echo "СБОРКА ИДЁТ: pid $pid в $cwd"; exit 0 ;;
    esac
done
exit 1
