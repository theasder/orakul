import OrakulCore

/// Поиск по прошлым звонкам в приложении складывает совпадения множествами
/// слов. Для русского запроса это и есть весь поиск: вторая половина —
/// эмбеддинг системной модели macOS, а она англоязычная.
///
/// Разбор слова здесь стоял такой: «термин словаря или слово как есть». Рядом
/// лежал комментарий «один и тот же шаг, что и в командной строке» — но шаг
/// был не тот: обрезки окончаний не было вовсе. «Развёртыванием» и
/// «развёртывание» оставались разными словами, пересечение пустым, и разговор
/// не находился. В командной строке то же самое чинилось дважды за эту ночь;
/// приложение при этом молчало, потому что ни одна проверка сюда не смотрела.
@Suite("Падежи в поиске по звонкам")
struct RecallCaseMatchingTests {

    private func matches(question: String, said: String) -> Bool {
        !DecisionRecallService.tokens(in: question)
            .intersection(DecisionRecallService.tokens(in: said)).isEmpty
    }

    @Test("вопрос в косвенном падеже сходится с речью в именительном",
          arguments: [
            ("что решили по развёртыванию", "развёртывание откладываем на сентябрь"),
            ("что там с обновлением", "обновление выкатим в среду"),
            ("вопрос по согласованию", "согласование затянулось"),
            ("что с годовым тарифом", "годовой тариф не трогаем"),
            ("по срокам договорились", "сроки сдвигаем на неделю"),
          ])
    func obliqueQuestionMatchesNominativeSpeech(question: String, said: String) {
        #expect(matches(question: question, said: said),
                "«\(question)» не пересеклось с «\(said)»")
    }

    /// Обратная сторона: разбор не должен склеивать всё подряд, иначе
    /// «нашлось» перестаёт что-либо значить.
    @Test("несвязанные слова не пересекаются")
    func unrelatedDoesNotMatch() {
        #expect(!matches(question: "что решили по корпоративу",
                         said: "развёртывание откладываем на сентябрь"))
    }

    /// Разбор общий с командной строкой — не на словах, а вызовом одной функции.
    @Test("приложение и командная строка приводят слово к одной основе")
    func appAndCommandLineAgree() {
        for word in ["развёртыванием", "годовым", "клиентов", "промпт"] {
            let inApp = DecisionRecallService.tokens(in: word)
            #expect(inApp == [RecallIndex.searchToken(for: word)],
                    "«\(word)»: приложение даёт \(inApp)")
        }
    }
}
